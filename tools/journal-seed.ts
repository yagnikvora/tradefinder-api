// Fill the trade journal with sample rows, so the page can be reviewed before a real signal has
// ever been recorded.  Run: npm run seed-journal      Undo: npm run seed-journal -- --clear
//
// WHY THIS EXISTS AND WHY IT IS TEMPORARY. The journal only gains rows when an alert channel
// fires and prices a contract; nothing is backfilled. That is correct behaviour and it means a
// fresh install shows an empty page with no way to tell a working journal from a broken one.
// This writes rows that look like real ones so the layout, the totals, the shadow cards, the
// channel filter and the edit dialog can all be seen at once.
//
// EVERY NUMBER IN HERE IS INVENTED. The symbols and spot prices are real and taken from the
// 2026-08-24 snapshot, so the strikes look sane; the premiums, fills, outcomes and excursions are
// generated. Nothing here was measured and none of it should ever be quoted as performance.
//
// DELETION IS THE POINT, so it is built in rather than left as a chore:
//
//   EVERY SAMPLE ROW CARRIES `MARKER` IN ITS NOTE, and that — not the id list — is what `--clear`
//   matches on. The first cut of this tool removed "whatever the generator produces today",
//   which was wrong in a way that only showed up once: editing the roster changed the ids, so a
//   clear after an edit deleted the rows the NEW code would have written and orphaned the ones
//   actually on disk. A real trade never carries the marker, so matching on it is both surgical
//   and immune to this file being edited between the seed and the clear.
//
//   IT CLEARS BOTH HALVES OF THE RECORD. `api/.env` has a DATABASE_URL, so the journal runs as a
//   mirror: local disk plus Neon. `journalBoot()` pushes local history the database has not seen
//   on the first journal request, which means these rows reach Neon as soon as the page is opened
//   — deleting the local file alone would leave them in the shared record and they would come
//   back on the next read. `--clear` deletes from disk, from Postgres, and from the retry queue.

