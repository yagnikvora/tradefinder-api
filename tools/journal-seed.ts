/**
 * What makes a row removable, and why there are two of them.
 *
 * `KEY_MARKER` is the one that counts. It sits in `contract.instrumentKey`, which no code path can
 * change: `JournalPatch` accepts only entry premium, exit premium, lots, note and reset, so the
 * contract is immutable once written. A real Upstox instrument key never looks like this.
 *
 * `MARKER` in the note is a convenience for reading a row on screen and NOT a reliable key — the
 * edit dialog sends `note` on every save, so using the fill editor on a sample row wipes it. That
 * is not hypothetical: it stranded a row through a `--clear` during review, which is why the
 * instrument key became the primary match rather than the note.
 *
 * Never change either without clearing first — an old marker on disk and a new one in the code is
 * exactly the orphaning these exist to prevent.
 */
const KEY_MARKER = 'NSE_FO|SAMPLE-';
const MARKER = 'SAMPLE ROW — generated by tools/journal-seed.ts';

/** Months a clear should sweep, whatever the generator currently produces. */
const SWEEP_MONTHS = ['2026-07', '2026-08', '2026-09'];

/** Read the same way the app reads them, so the money columns match what the page computes. */
const CHARGE_PER_LOT = Number(process.env.JOURNAL_CHARGE_PER_LOT) || 120;
const LOTS = Number(process.env.JOURNAL_LOTS) || 1;
const TP = 0.80;
const SL = 0.50;
const SQUARE_OFF_MIN = 360;

